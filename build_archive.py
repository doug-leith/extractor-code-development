def _load_verdicts_data():
    spec = importlib.util.spec_from_file_location("verdicts_data", VERDICTS_DATA_SRC)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def public_verdicts_data_source(mod):
    in_scope_sids = {sid for sid, m in mod.SESSION_META.items() if m[1] == "in_scope"}
    session_meta = {sid: m for sid, m in mod.SESSION_META.items() if sid in in_scope_sids}
    verdicts = {k: v for k, v in mod.VERDICTS.items() if k[0] in in_scope_sids}
    extra_episodes = [e for e in mod.EXTRA_EPISODES if e[0] in in_scope_sids]

    return f'''"""Hand-verified session/episode classification data for
build_results_csv.py -- in_scope sessions only. Generated by
reproducibility_archive/build_archive.py from the real (internal)
verdicts_data.py, which also carries excluded sessions' rationale/evidence
(audit-trail material kept out of this archive) -- see that file's own
docstring.

dir_tag in SESSION_META is "june" (data/dataset/output/sessions/) or
"recov" (session_recovery_batch/, not archived -- every session below is
in_scope, so this is always "june").
"""

SESSION_META = {pprint.pformat(session_meta)}

VERDICTS = {pprint.pformat(verdicts)}

EXTRA_EPISODES = {pprint.pformat(extra_episodes)}
'''


