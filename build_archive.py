def public_raw_scan_source(src_path, scope_by_sid):
    records = json.loads(src_path.read_text())
    in_scope = [r for r in records if scope_by_sid.get(r["session"]) == "in_scope"]
    return json.dumps(in_scope, indent=2)


def public_all_pytest_runs_source(scope_by_sid):
    with open(PDC_DIR / "all_pytest_runs.csv", newline="") as f:
        rows = list(csv.DictReader(f))
    in_scope_rows = [r for r in rows if scope_by_sid.get(r["session"]) == "in_scope"]
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=list(rows[0].keys()))
    w.writeheader()
    w.writerows(in_scope_rows)
    return buf.getvalue()

